import type { ImpactResult } from "./types";

/**
 * Normalizes Devanagari digits (० through ९) to ASCII digits (0 through 9).
 *
 * @param text - Input string possibly containing Indic Devanagari numerals.
 * @returns Normalized text with ASCII numeric representations.
 */
export function normalizeDevanagariDigits(text: string): string {
  return text.replace(/[\u0966-\u096F]/g, (char) =>
    String.fromCharCode(char.charCodeAt(0) - 0x0966 + 48),
  );
}

/**
 * Configuration options for number extraction and whitelist validation.
 */
export interface NumberWhitelistOptions {
  /** If true, ignores list numbering like "1.", "2.", "1)", "2)" */
  readonly ignoreListNumbering?: boolean;
  /** If true, ignores 4-digit Gregorian calendar years between 1900 and 2099 */
  readonly ignoreYears?: boolean;
  /** If true, ignores ordinal suffixes like "1st", "2nd", "3rd", "4th" */
  readonly ignoreOrdinals?: boolean;
  /** Tolerance threshold for float equality (default 0.05) */
  readonly tolerance?: number;
}

/**
 * Collects the deterministic set of numbers produced by the engine, including
 * standard rounding variants (integers, single decimals, and percentages).
 *
 * @param results - Array of evaluated ImpactResult objects.
 * @param extras - Optional auxiliary numbers (e.g. ambient PM2.5, WHO 15 guideline, room volume).
 * @returns Set containing all authorized numerical values.
 */
export function collectAllowedNumbers(
  results: readonly ImpactResult[],
  extras: readonly number[] = [],
): Set<number> {
  const allowed = new Set<number>();

  function register(n: number | undefined): void {
    if (n === undefined || !Number.isFinite(n)) {
      return;
    }
    allowed.add(n);
    allowed.add(Math.round(n));
    allowed.add(Math.floor(n));
    allowed.add(Math.ceil(n));
    allowed.add(Number(n.toFixed(1)));
    allowed.add(Number(n.toFixed(2)));
  }

  for (const res of results) {
    if (res.displayMode === "numeric") {
      register(res.baseline);
      register(res.scenario);
      register(res.deltaLow);
      register(res.deltaLikely);
      register(res.deltaHigh);
      register(res.costInr);
      register(res.minutes);

      // Percentage reduction relative to baseline
      if (res.baseline && res.baseline > 0 && res.deltaLikely !== undefined) {
        const pct = (res.deltaLikely / res.baseline) * 100;
        register(pct);
      }
    }
  }

  for (const extra of extras) {
    register(extra);
  }

  return allowed;
}

/**
 * Extracts and returns any numerical figures present in a text that were not
 * produced by the pure decision engine.
 *
 * Used in Phase 2.3 as an automated guard to reject LLM generations that hallucinate numbers.
 *
 * @param text - Candidate text generated by LLM or external source.
 * @param allowed - Whitelist set created by collectAllowedNumbers.
 * @param options - Extraction filtering options.
 * @returns Array of disallowed extracted numbers.
 */
export function findDisallowedNumbers(
  text: string,
  allowed: Set<number>,
  options: NumberWhitelistOptions = {},
): number[] {
  const {
    ignoreListNumbering = true,
    ignoreYears = true,
    ignoreOrdinals = true,
    tolerance = 0.05,
  } = options;

  let cleaned = normalizeDevanagariDigits(text);

  // Normalize range hyphens e.g. "150-170" or "10 - 20" -> "150 to 170"
  cleaned = cleaned.replace(/(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)/g, "$1 to $2");

  // Mask standard domain designations, masks, and volumetric units
  cleaned = cleaned.replace(/PM\s*2\.5/gi, "PM_TWO_POINT_FIVE");
  cleaned = cleaned.replace(/PM\s*10/gi, "PM_TEN");
  cleaned = cleaned.replace(/N95/gi, "RESPIRATOR_N95");
  cleaned = cleaned.replace(/FFP2/gi, "RESPIRATOR_FFP2");
  cleaned = cleaned.replace(/KN95/gi, "RESPIRATOR_KN95");
  cleaned = cleaned.replace(/m3|m³|µg\/m3|ug\/m3|µg\/m³|ug\/m³/gi, " ");

  // Strip list numbering at line starts or word boundaries e.g. "1. ", "2) "
  if (ignoreListNumbering) {
    cleaned = cleaned.replace(/(?:^|\n|\s)\d+[\.)]\s+/g, " ");
  }

  // Strip ordinal numbers e.g. "1st", "2nd", "3rd", "4th"
  if (ignoreOrdinals) {
    cleaned = cleaned.replace(/\b\d+(?:st|nd|rd|th)\b/gi, " ");
  }

  // Remove commas inside numbers e.g. "4,500" -> "4500"
  cleaned = cleaned.replace(/(\d+),(\d+)/g, "$1$2");

  // Match standalone number tokens (integers or decimals, optionally negative)
  const tokenRegex = /(?<![a-zA-Z0-9_])-?\d+(?:\.\d+)?(?![a-zA-Z0-9_])/g;
  const matches = cleaned.match(tokenRegex) ?? [];
  const disallowed: number[] = [];

  for (const matchStr of matches) {
    const num = Number.parseFloat(matchStr);
    if (!Number.isFinite(num)) {
      continue;
    }

    // Filter Gregorian calendar years
    if (ignoreYears && num >= 1900 && num <= 2099 && Number.isInteger(num)) {
      continue;
    }

    let isPermitted = false;
    for (const validNum of allowed) {
      if (Math.abs(validNum - num) <= tolerance) {
        isPermitted = true;
        break;
      }
    }

    if (!isPermitted) {
      disallowed.push(num);
    }
  }

  return disallowed;
}
