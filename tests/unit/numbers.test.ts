import { describe, expect, it } from "vitest";
import {
  collectAllowedNumbers,
  findDisallowedNumbers,
  normalizeDevanagariDigits,
} from "@/core/numbers";
import type { ImpactResult } from "@/core/types";

describe("LLM Number Whitelist Guard", () => {
  describe("Devanagari numeral normalization", () => {
    it("converts all Indic numerals to standard ASCII digits", () => {
      expect(normalizeDevanagariDigits("०१२३४५६७८९")).toBe("0123456789");
      expect(normalizeDevanagariDigits("पीएम २.५ सांद्रता १५० है")).toBe("पीएम 2.5 सांद्रता 150 है");
    });
  });

  describe("Number collection and extraction", () => {
    const mockResults: ImpactResult[] = [
      {
        actionId: "purifier",
        displayMode: "numeric",
        baseline: 200,
        scenario: 40,
        deltaLow: 150,
        deltaLikely: 160,
        deltaHigh: 170,
        unit: "ug/m3",
        assumptions: [],
        sources: [],
        confidence: "high",
        costInr: 4500,
      },
      {
        actionId: "mask",
        displayMode: "directional",
        direction: "reduces",
        assumptions: [],
        sources: [],
        confidence: "medium",
      },
    ];

    it("collects engine outputs, rounding variants, and reduction percentages", () => {
      const allowed = collectAllowedNumbers(mockResults, [15, 24]);

      // Base numbers
      expect(allowed.has(200)).toBe(true);
      expect(allowed.has(40)).toBe(true);
      expect(allowed.has(160)).toBe(true);
      expect(allowed.has(4500)).toBe(true);

      // Extras
      expect(allowed.has(15)).toBe(true);
      expect(allowed.has(24)).toBe(true);

      // Percentage reduction: 160 / 200 = 80%
      expect(allowed.has(80)).toBe(true);
    });

    it("permits allowed numbers in diverse textual representations", () => {
      const allowed = collectAllowedNumbers(mockResults, [15]);
      const validText = `
        Operating the purifier reduces indoor PM2.5 from 200 down to 40 ug/m3,
        achieving a likely reduction of 160 ug/m3 (an 80% improvement).
        This brings indoor levels closer to the WHO guideline of 15 ug/m3.
        Estimated cost is 4,500 INR.
      `;

      const disallowed = findDisallowedNumbers(validText, allowed);
      expect(disallowed).toEqual([]);
    });

    it("rejects hallucinated or invented numbers not generated by the engine", () => {
      const allowed = collectAllowedNumbers(mockResults, [15]);
      const hallucinatedText = `
        This intervention will reduce PM2.5 by 92.5% and prevent 47 acute attacks.
        Tested across 350 homes.
      `;

      const disallowed = findDisallowedNumbers(hallucinatedText, allowed);
      expect(disallowed).toContain(92.5);
      expect(disallowed).toContain(47);
      expect(disallowed).toContain(350);
    });

    it("detects disallowed figures expressed in Devanagari numerals", () => {
      const allowed = collectAllowedNumbers(mockResults, [15]);
      const devanagariText = "वायु गुणवत्ता में ९५% की कमी आएगी।"; // 95% is invented

      const disallowed = findDisallowedNumbers(devanagariText, allowed);
      expect(disallowed).toContain(95);
    });

    it("correctly handles ranges and thousands separators", () => {
      const allowed = collectAllowedNumbers(mockResults, [150, 170]);
      const textWithRange = "Expected delta is between 150-170 ug/m3 for 4,500 INR.";

      const disallowed = findDisallowedNumbers(textWithRange, allowed);
      expect(disallowed).toEqual([]);
    });

    it("ignores list numbers and calendar years by default", () => {
      const allowed = collectAllowedNumbers(mockResults);
      const formattedText = `
        1. Keep windows closed during 2026 winter season.
        2. Operate purifier with likely 160 reduction.
      `;

      const disallowed = findDisallowedNumbers(formattedText, allowed, {
        ignoreListNumbering: true,
        ignoreYears: true,
      });

      expect(disallowed).toEqual([]);
    });

    it("rejects ranges like 40-50% or 'reduce by 40 to 50 percent' when neither is in allowed set", () => {
      const restrictedAllowed = new Set<number>([160, 200]); // strictly 160 and 200

      const rangeText1 = "This strategy achieves a 40-50% reduction in exposure.";
      const disallowed1 = findDisallowedNumbers(rangeText1, restrictedAllowed);
      expect(disallowed1).toContain(40);
      expect(disallowed1).toContain(50);

      const rangeText2 = "Expect to reduce by 40 to 50 percent during peak hours.";
      const disallowed2 = findDisallowedNumbers(rangeText2, restrictedAllowed);
      expect(disallowed2).toContain(40);
      expect(disallowed2).toContain(50);
    });

    it("does not cause false rejections for PM2.5, N95, or calendar years", () => {
      const allowed = new Set<number>([160]);
      const validText = `
        In 2026, outdoor PM2.5 is high, so wear an N95 respirator.
        This provides a 160 ug/m3 benefit.
      `;

      const disallowed = findDisallowedNumbers(validText, allowed, {
        ignoreYears: true,
      });

      expect(disallowed).toEqual([]);
    });
  });
});
